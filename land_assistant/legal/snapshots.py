"""Provenance of local law snapshots; a check date is never today's assurance."""
from datetime import date


def snapshot_notice(as_of):
    label=date.fromisoformat(as_of).strftime('%d.%m.%Y')
    return f'Сохранённые материалы проверены по состоянию на {label}. Изменения после этой даты не проверены.'


SNAPSHOT_POLICY='Фрагменты с snapshot_as_of — проверенные локальные снимки на указанную дату, а не подтверждение сегодняшней редакции. Их разрешено использовать для ограниченного ответа по сохранённой редакции; сама прошедшая дата не является отсутствием нормативных оснований. Не объявляй такие выводы подтверждённо актуальными на сегодня. Если предоставлена более новая проверенная редакция того же положения, руководствуйся ею. При несовместимых материалах обозначь ограничение и не выдумывай действующий вариант.'
